import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { checked } from '../src/process.mjs';
import { captureSnapshot } from '../src/snapshot.mjs';
import { projectInventory, captureProjectBatch } from '../src/project-snapshot.mjs';
import { createRetrievalScope } from '../src/retrieval-scope.mjs';
import { createEvidenceReceipts } from '../src/evidence-receipts.mjs';
import { validateEvidenceReference } from '../src/evidence-reference.mjs';

const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const CONTEXT_PATH = 'context.js';
const CHANGED_PATHS = ['legacy.js', 'unicode.js', 'wide.js'];
const ALL_PATHS = [...CHANGED_PATHS, CONTEXT_PATH];
const CONTEXT_TEXT = '// 中文\r\nexport const value = "你好";\r\n';

// Actual GBK bytes, not UTF-8 generated by the decoder under test:
// 中文 = d6 d0 ce c4; 你好 = c4 e3 ba c3. ASCII fragments stay byte-for-byte.
const chineseGbk = Buffer.from([0xd6, 0xd0, 0xce, 0xc4]);
const helloGbk = Buffer.from([0xc4, 0xe3, 0xba, 0xc3]);
function legacyBytes(version) {
  return Buffer.concat([
    Buffer.from('// ', 'ascii'), chineseGbk,
    Buffer.from('\r\nimport { value } from "./context.js";\r\nexport const message = "', 'ascii'),
    helloGbk, Buffer.from('"; // ' + version + '\r\n', 'ascii'),
  ]);
}
const contextBytes = Buffer.concat([
  Buffer.from('// ', 'ascii'), chineseGbk,
  Buffer.from('\r\nexport const value = "', 'ascii'), helloGbk,
  Buffer.from('";\r\n', 'ascii'),
]);
function sourceText(name, version) {
  if (name === CONTEXT_PATH) return CONTEXT_TEXT;
  if (name === 'legacy.js') return '// 中文\r\nimport { value } from "./context.js";\r\nexport const message = "你好"; // ' + version + '\r\n';
  if (name === 'unicode.js') return '// 中文 UTF-8\r\nexport const 消息 = "你好"; // ' + version + '\r\n';
  return '// 中文 UTF-16\r\nexport const wide = ' + version + ';\r\n';
}
function sourceBytes(name, version) {
  if (name === CONTEXT_PATH) return contextBytes;
  if (name === 'legacy.js') return legacyBytes(version);
  if (name === 'unicode.js') return Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), Buffer.from(sourceText(name, version), 'utf8')]);
  return Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(sourceText(name, version), 'utf16le')]);
}
function assertContent(content, name, version) {
  assert.ok(content, 'missing captured content for ' + name);
  assert.equal(content.text, sourceText(name, version));
  assert.equal(content.encoding, name === 'legacy.js' || name === CONTEXT_PATH ? 'gbk' : name === 'wide.js' ? 'utf-16le' : 'utf-8');
  assert.equal(content.hash, digest(sourceBytes(name, version)));
  assert.equal(content.bytes, sourceBytes(name, version).length);
}
function assertChanged(snapshot, oldVersion, newVersion) {
  assert.equal(snapshot.files.length, CHANGED_PATHS.length);
  for (const name of CHANGED_PATHS) {
    const file = snapshot.files.find(item => item.path === name);
    assert.equal(file?.eligibility, 'reviewable', JSON.stringify(file));
    assertContent(file.left, name, oldVersion);
    assertContent(file.right, name, newVersion);
  }
}

async function fixture(t, vcs) {
  const prefix = 'dsh-source-encoding-' + vcs + '-';
  const directory = await mkdtemp(path.join(os.tmpdir(), prefix));
  t.after(async () => {
    // Delete only the absolute, uniquely allocated fixture root, never a repo path.
    assert.equal(path.dirname(directory), path.resolve(os.tmpdir()));
    assert.ok(path.basename(directory).startsWith(prefix));
    await rm(directory, { recursive: true, force: true });
  });
  const root = path.join(directory, 'wc');
  const command = (...args) => checked(vcs, vcs === 'svn' ? ['--non-interactive', ...args] : args, { cwd: root });
  if (vcs === 'git') {
    await mkdir(root);
    await command('init', '-q');
    await command('config', 'user.name', 'Encoding Integration');
    await command('config', 'user.email', 'encoding@example.invalid');
    await command('config', 'core.autocrlf', 'false');
    await command('config', 'commit.gpgsign', 'false');
  } else {
    const repository = path.join(directory, 'repo');
    await checked('svnadmin', ['create', repository]);
    await checked('svn', ['--non-interactive', 'checkout', pathToFileURL(repository).href, root]);
  }
  const put = (name, bytes) => writeFile(path.join(root, name), bytes);
  const writeVersion = async version => {
    for (const name of CHANGED_PATHS) await put(name, sourceBytes(name, version));
  };
  const commit = async message => {
    if (vcs === 'git') {
      await command('add', '--all');
      await command('commit', '-qm', message);
      return (await command('rev-parse', 'HEAD')).toString('ascii').trim();
    }
    await command('commit', '-m', message);
    return undefined;
  };
  await writeVersion(1);
  await put(CONTEXT_PATH, contextBytes);
  if (vcs === 'svn') {
    // Explicitly suppress user auto-props (especially eol-style/mime-type).
    await command('add', '--no-auto-props', ...ALL_PATHS);
  }
  const base = await commit('encoding baseline');
  return { root, command, put, writeVersion, commit, base };
}

function assertRetrieval(snapshot, name, side, expected) {
  const scope = createRetrievalScope(snapshot);
  const source = scope.catalog().find(item => item.path === name && item.side === side);
  assert.ok(source, 'missing ' + name + ' ' + side + ' retrieval source');
  const search = scope.search({ query: '你好', sourceIds: [source.id] });
  assert.equal(search.matches.length, 1);
  assert.equal(search.matches[0].line, name === 'legacy.js' ? 3 : 2);
  const receipts = createEvidenceReceipts(scope.read);
  const receipt = receipts.read({ id: source.id, start: 1, count: 20 });
  assert.equal(receipt.text, expected);
  assert.equal(receipt.hash, digest(Buffer.from(expected, 'utf8')));
  assert.equal(receipt.snapshotId, snapshot.id);
  const reference = receipts.resolve({ receiptId: receipt.receiptId });
  assert.equal(validateEvidenceReference(reference, scope.read).status, 'references-validated');
  assert.throws(() => validateEvidenceReference({ ...reference, text: expected.replaceAll('\r\n', '\n') }, scope.read), /does not match approved snapshot/);
  assert.equal(scope.usage().calls, 4);
  return reference;
}

for (const vcs of ['git', 'svn']) {
  test(vcs + ' working capture preserves mixed source encodings, CRLF evidence and raw-byte identity', async t => {
    const { root, command, put, writeVersion } = await fixture(t, vcs);
    await writeVersion(2);
    const options = { contextPaths: [CONTEXT_PATH], autoContext: true };
    // SVN XML attribute order is nondeterministic; compare stable status columns.
    const status = () => command(...(vcs === 'git' ? ['status', '--porcelain=v1', '-z'] : ['status']));
    const before = await status();
    const snapshot = await captureSnapshot(root, options);
    assertChanged(snapshot, 1, 2);
    assertContent(snapshot.context.find(item => item.path === CONTEXT_PATH), CONTEXT_PATH);
    const reference = assertRetrieval(snapshot, 'legacy.js', 'new', sourceText('legacy.js', 2));
    assertRetrieval(snapshot, CONTEXT_PATH, 'context', CONTEXT_TEXT);
    assert.equal((await captureSnapshot(root, options)).id, snapshot.id);
    assert.deepEqual(await status(), before);
    for (const name of ALL_PATHS) assert.deepEqual(await readFile(path.join(root, name)), sourceBytes(name, 2));

    // Text and retrieval hashes stay equal; authorization identity must not.
    await put('legacy.js', Buffer.from(sourceText('legacy.js', 2), 'utf8'));
    const transcoded = await captureSnapshot(root, options);
    const changed = transcoded.files.find(item => item.path === 'legacy.js');
    assert.equal(changed.right.text, snapshot.files.find(item => item.path === 'legacy.js').right.text);
    assert.equal(changed.right.encoding, 'utf-8');
    assert.equal(changed.right.hash, digest(Buffer.from(sourceText('legacy.js', 2), 'utf8')));
    assert.notEqual(changed.right.hash, snapshot.files.find(item => item.path === 'legacy.js').right.hash);
    assert.notEqual(transcoded.id, snapshot.id);
    const nextScope = createRetrievalScope(transcoded);
    assert.throws(() => validateEvidenceReference(reference, nextScope.read), /snapshotId/);
    await put('legacy.js', legacyBytes(2));

    // Also exercise raw-byte limits, rather than a decoded-character count.
    const limited = await captureSnapshot(root, { selectedPaths: ['legacy.js'], maxFileBytes: legacyBytes(2).length - 1 });
    assert.equal(limited.files.find(item => item.path === 'legacy.js').eligibility, 'blocked');
    assert.deepEqual(await readFile(path.join(root, 'legacy.js')), legacyBytes(2));
  });

  test(vcs + ' fixed history captures GBK blobs and context without consulting local source', async t => {
    const { root, put, writeVersion, commit, base } = await fixture(t, vcs);
    await writeVersion(2);
    const target = await commit('encoding target');
    const options = {
      ...(vcs === 'git' ? { baseRevision: base, targetRevision: target } : { svnBaseRevision: '1', svnTargetRevision: '2' }),
      contextPaths: [CONTEXT_PATH], autoContext: true,
    };
    const snapshot = await captureSnapshot(root, options);
    assertChanged(snapshot, 1, 2);
    const context = snapshot.context.find(item => item.path === CONTEXT_PATH);
    assertContent(context, CONTEXT_PATH);
    assert.equal(context.oldText, CONTEXT_TEXT);
    assertRetrieval(snapshot, 'legacy.js', 'old', sourceText('legacy.js', 1));
    assertRetrieval(snapshot, 'legacy.js', 'new', sourceText('legacy.js', 2));
    assertRetrieval(snapshot, CONTEXT_PATH, 'context-old', CONTEXT_TEXT);
    assertRetrieval(snapshot, CONTEXT_PATH, 'context', CONTEXT_TEXT);
    if (vcs === 'svn') {
      const legacy = snapshot.files.find(item => item.path === 'legacy.js');
      assert.equal(legacy.svnSources.old.hash, digest(legacyBytes(1)));
      assert.equal(legacy.svnSources.new.hash, digest(legacyBytes(2)));
      assert.equal(context.svnSource.hash, digest(contextBytes));
      assert.equal(context.oldSvnSource.hash, digest(contextBytes));
    }
    for (const name of ALL_PATHS) await put(name, Buffer.from([0xff]));
    const repeated = await captureSnapshot(root, options);
    assert.equal(repeated.id, snapshot.id);
    for (const name of ALL_PATHS) assert.deepEqual(await readFile(path.join(root, name)), Buffer.from([0xff]));
  });

  test(vcs + ' project capture includes unchanged GBK/UTF8/UTF16 tracked sources and binds transcoding', async t => {
    const { root, put } = await fixture(t, vcs);
    const inventory = await projectInventory(root, vcs);
    const snapshot = await captureProjectBatch(inventory, ALL_PATHS);
    assert.equal(snapshot.files.length, ALL_PATHS.length);
    for (const name of ALL_PATHS) {
      const file = snapshot.files.find(item => item.path === name);
      assert.equal(file.eligibility, 'reviewable', JSON.stringify(file));
      assert.equal(file.left.text, '');
      assertContent(file.right, name, 1);
      assert.deepEqual(await readFile(path.join(root, name)), sourceBytes(name, 1));
    }
    const reference = assertRetrieval(snapshot, 'legacy.js', 'new', sourceText('legacy.js', 1));
    await put('legacy.js', Buffer.from(sourceText('legacy.js', 1), 'utf8'));
    // Reuse the same tracked inventory to isolate source bytes from index/status changes.
    const transcoded = await captureProjectBatch(inventory, ALL_PATHS);
    assert.notEqual(transcoded.id, snapshot.id);
    assert.equal(transcoded.files.find(item => item.path === 'legacy.js').right.text, sourceText('legacy.js', 1));
    assert.throws(() => validateEvidenceReference(reference, createRetrievalScope(transcoded).read), /snapshotId/);
  });
}

test('Git staged and unstaged captures decode the approved index side independently of worktree encoding', async t => {
  const { root, command, put, writeVersion } = await fixture(t, 'git');
  await writeVersion(2);
  await command('add', '--', ...CHANGED_PATHS);
  await put('legacy.js', Buffer.from(sourceText('legacy.js', 3), 'utf8'));
  const staged = await captureSnapshot(root, { changeScope: 'staged', contextPaths: ['legacy.js'] });
  assertChanged(staged, 1, 2);
  assertContent(staged.context[0], 'legacy.js', 2);
  assertRetrieval(staged, 'legacy.js', 'new', sourceText('legacy.js', 2));
  const unstaged = await captureSnapshot(root, { changeScope: 'unstaged' });
  assert.equal(unstaged.files.length, 1);
  const legacy = unstaged.files[0];
  assert.equal(legacy.eligibility, 'reviewable', JSON.stringify(legacy));
  assertContent(legacy.left, 'legacy.js', 2);
  assert.equal(legacy.right.text, sourceText('legacy.js', 3));
  assert.equal(legacy.right.encoding, 'utf-8');
  assert.equal(legacy.right.hash, digest(Buffer.from(sourceText('legacy.js', 3), 'utf8')));
});
